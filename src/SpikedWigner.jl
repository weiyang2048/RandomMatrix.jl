# Spiked Wigner models and the additive BBP phase transition.
#
# Model: M = sigma * W / sqrt(n) + A, where W is a Wigner matrix (entries
# of variance sigma^2 before the 1/sqrt(n) scaling, GOE/GUE conventions:
# semicircle bulk on [-2 sigma, 2 sigma]) and A is a fixed finite-rank
# deformation with a spike theta (an eigenvalue of A). The spike produces
# an outlier eigenvalue of M only above the threshold |theta| > sigma;
# below it the spike is absorbed by the semicircle bulk and is
# undetectable. This is the additive analogue of the spiked covariance
# layer in SpikedCovariance.jl and of the spiked MANOVA layer in
# SpikedManova.jl, hence the parallel `wigner`-prefixed names.
#
# References: Capitaine, Donati-Martin & Feral, "The largest eigenvalues
# of finite rank deformations of large Wigner matrices: convergence and
# nonuniversality of the fluctuations", Ann. Probab. 37(1), 2009, 1-47
# (location: Thm. 2.1; Gaussian fluctuations: Thm. 2.3 and eq. (2.5)-(2.6);
# non-Gaussian coordinate-direction fluctuations: Thm. 2.2);
# Capitaine & Donati-Martin, Ann. Inst. H. Poincare Probab. Statist.
# 48(1), 2012, 107-133 (CLT companion).

export wignerThreshold, wignerSpikeLocation, wignerSpikeOverlap,
    wignerEstimateSpike, wignerSpikeVariance, randSpikedWigner

function _wigner_check(σ::Real)
    σ > 0 || throw(ArgumentError("noise scale sigma must be positive, got sigma = $σ"))
    return nothing
end

"""
    wignerThreshold(; sigma=1.0)

Critical spike size for the BBP phase transition in a spiked Wigner
model: a spike `theta` of the deformation produces an outlier eigenvalue
of `sigma * W / sqrt(n) + A` only if `|theta| > sigma`, where `sigma^2`
is the variance of the (unscaled) Wigner entries, so the semicircle bulk
is supported on `[-2 sigma, 2 sigma]`.
"""
function wignerThreshold(; σ::Real=1.0)
    _wigner_check(σ)
    return float(σ)
end

"""
    wignerSpikeLocation(theta; sigma=1.0)

Almost-sure limit of the sample eigenvalue generated by a spike `theta`
of the deformation in a spiked Wigner model with noise scale `sigma`
(semicircle bulk on `[-2 sigma, 2 sigma]`):

    theta + sigma^2 / theta     if |theta| > sigma

For `|theta| <= sigma` the spike sticks to the nearer semicircle edge
`sign(theta) * 2 sigma` (with `theta = 0` returning `2 sigma`), which is
what this returns.
"""
function wignerSpikeLocation(θ::Real; σ::Real=1.0)
    _wigner_check(σ)
    abs(θ) <= σ && return θ < 0 ? -2.0 * σ : 2.0 * σ
    return θ + σ^2 / θ
end

"""
    wignerSpikeOverlap(theta; sigma=1.0)

Almost-sure limit of the squared overlap `|dot(u_hat, v)|^2` between the
sample eigenvector of the outlier and the spike direction `v`, for a
spike `theta` with noise scale `sigma`:

    1 - sigma^2 / theta^2     if |theta| > sigma

Zero at or below the threshold [`wignerThreshold`](@ref): the sample
eigenvector is asymptotically orthogonal to the spike direction.
"""
function wignerSpikeOverlap(θ::Real; σ::Real=1.0)
    _wigner_check(σ)
    abs(θ) <= σ && return 0.0
    return 1 - σ^2 / θ^2
end

"""
    wignerEstimateSpike(lambda; sigma=1.0)

Estimate the spike `theta` from an observed outlier sample eigenvalue
`lambda`, by inverting [`wignerSpikeLocation`](@ref):

    theta = (lambda + sign(lambda) * sqrt(lambda^2 - 4 sigma^2)) / 2

For `lambda` inside the semicircle bulk `[-2 sigma, 2 sigma]` the spike
is not identifiable and the threshold value on that side,
`sign(lambda) * sigma` (with `lambda = 0` returning `sigma`), is
returned.
"""
function wignerEstimateSpike(λ::Real; σ::Real=1.0)
    _wigner_check(σ)
    abs(λ) <= 2σ && return λ < 0 ? -float(σ) : float(σ)
    return (λ + sign(λ) * sqrt(λ^2 - 4 * σ^2)) / 2
end

"""
    wignerSpikeVariance(theta, n; sigma=1.0, real=true, m4=nothing)

Asymptotic variance of the outlier sample eigenvalue generated by a
supercritical spike `theta` (`|theta| > sigma`) in an `n x n` spiked
Wigner model. Returns `NaN` at or below the threshold
[`wignerThreshold`](@ref), where the fluctuations are Tracy-Widom
rather than Gaussian.

By default (Gaussian noise, or any delocalized spike direction) the
fluctuations are Gaussian with (Capitaine-Donati-Martin-Feral 2009,
Thm. 2.3)

    Var(lambda_hat) = c * sigma^2 * (1 - sigma^2 / theta^2) / n,

with `c = 2` for real data (`real=true`) and `c = 1` for complex data:
`sqrt(n) (lambda_hat - wignerSpikeLocation(theta))` is asymptotically
centred normal with variance `n * Var(lambda_hat)`.

The fluctuations are *non-universal* when the spike points along a
coordinate direction `v = e_i` and the entries are non-Gaussian
(Capitaine-Donati-Martin-Feral 2009, Thm. 2.2): the limiting law of
`sqrt(n) (lambda_hat - rho) / (1 - sigma^2 / theta^2)` is then the
convolution of the diagonal-entry law with a Gaussian, and its variance
picks up a fourth-cumulant term. Passing `m4`, the fourth moment of the
noise entries (`E[W_ij^4]` in the real case, `E[abs(W_ij)^4]` in the
complex case, for the unscaled entries of variance `sigma^2`; Gaussian
values `3 sigma^4` real, `2 sigma^4` complex), returns the variance of
that limiting law:

    Var(lambda_hat) = (1 - sigma^2 / theta^2)^2 *
        (c * sigma^2 + kappa / theta^2 + c * sigma^4 / (theta^2 - sigma^2)) / n,

where `kappa = m4 - 3 sigma^4` (real) or `kappa = m4 - 2 sigma^4`
(complex). At the Gaussian value of `m4` this reduces exactly to the
default formula above.
"""
function wignerSpikeVariance(θ::Real, n::Integer; σ::Real=1.0,
                              real::Bool=true, m4::Union{Real,Nothing}=nothing)
    _wigner_check(σ)
    n >= 1 || throw(ArgumentError("matrix size n must be positive, got n = $n"))
    abs(θ) <= σ && return NaN
    s2 = float(σ)^2
    c = real ? 2.0 : 1.0
    if m4 === nothing
        v = c * s2 * (1 - s2 / θ^2)
    else
        κ = m4 - (real ? 3 * s2^2 : 2 * s2^2)
        v = (1 - s2 / θ^2)^2 * (c * s2 + κ / θ^2 + c * s2^2 / (θ^2 - s2))
    end
    return v / n
end

"""
    randSpikedWigner(n, spikes; sigma=1.0)

Sample an `n x n` spiked Wigner matrix
`sigma * W / sqrt(n) + sum_k theta_k v_k v_k'`, where `W` is a GOE
matrix (see [`GOE`](@ref), sampled with `norm=true`, so the bulk follows
the semicircle law on `[-2 sigma, 2 sigma]`), `spikes` is a vector of
spike sizes `theta_k` (positive spikes separate above the bulk,
negative ones below, each only if `|theta_k| > sigma`), and the spike
directions `v_k` are orthonormal and Haar-random. Returns a symmetric
`n x n` matrix.

# Examples
```julia
M = randSpikedWigner(400, [2.0])
eigmax(M)   # near wignerSpikeLocation(2.0) = 2.5
```
"""
function randSpikedWigner(n::Integer, spikes::AbstractVector{<:Real};
                          σ::Real=1.0)
    _wigner_check(σ)
    k = length(spikes)
    k < n || throw(ArgumentError("need fewer spikes than dimensions"))
    M = Matrix(σ * rand(GOE(n), norm=true))
    if k > 0
        Q = Matrix(qr(randn(n, n)).Q)[:, 1:k]
        M .+= Q * Diagonal(collect(float.(spikes))) * Q'
    end
    return Symmetric(M)
end
