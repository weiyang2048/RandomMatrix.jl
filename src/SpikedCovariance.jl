# Spiked covariance models and the BBP phase transition.
#
# Model: data X (p x n) with population covariance Sigma whose eigenvalues are
# a bulk at sigma^2 plus a few larger "spikes" l. With gamma = p/n, a spike
# produces an outlier sample eigenvalue only above the Baik-Ben Arous-Peche
# threshold l > sigma^2 (1 + sqrt(gamma)); its sample eigenvector then keeps a
# positive overlap with the population direction. Below the threshold the
# spike is absorbed by the Marcenko-Pastur bulk and is undetectable.
#
# References: Baik, Ben Arous & Peche (2005); Paul (2007) for fluctuations;
# Benaych-Georges & Nadakuditi (2011, 2012) for the rectangular case.

export bbpThreshold, spikeLocation, spikeOverlap, estimateSpike, spikeVariance,
    svdThreshold, svdSpikeLocation, svdSpikeOverlaps, randSpikedCovariance

"""
    bbpThreshold(gamma; sigma=1.0)

Critical population eigenvalue for the BBP phase transition in a spiked
covariance model with aspect ratio `gamma = p/n` and bulk (noise) variance
`sigma^2`. A population spike `l` yields an outlier sample eigenvalue only if
`l > bbpThreshold(gamma) = sigma^2 * (1 + sqrt(gamma))`.
"""
bbpThreshold(γ::Real; σ::Real=1.0) = σ^2 * (1 + sqrt(γ))

"""
    spikeLocation(l, gamma; sigma=1.0)

Almost-sure limit of the sample eigenvalue generated by a population spike
`l` (an eigenvalue of the population covariance, bulk at `sigma^2`) with
aspect ratio `gamma = p/n`:

    l * (1 + gamma * sigma^2 / (l - sigma^2))     if l > sigma^2 (1 + sqrt(gamma))

Below the BBP threshold the spike sticks to the upper Marcenko-Pastur edge
`sigma^2 (1 + sqrt(gamma))^2`, which is what this returns.
"""
function spikeLocation(l::Real, γ::Real; σ::Real=1.0)
    s = σ^2
    l <= bbpThreshold(γ; σ) && return s * (1 + sqrt(γ))^2
    return l * (1 + γ * s / (l - s))
end

"""
    spikeOverlap(l, gamma; sigma=1.0)

Almost-sure limit of the squared overlap `|dot(u_hat, u)|^2` between the
sample eigenvector of the outlier and its population counterpart, for a
population spike `l` with aspect ratio `gamma = p/n` and bulk variance
`sigma^2`:

    (1 - gamma * sigma^4 / (l - sigma^2)^2) / (1 + gamma * sigma^2 / (l - sigma^2))

Zero below the BBP threshold: the sample eigenvector is asymptotically
orthogonal to the population direction.
"""
function spikeOverlap(l::Real, γ::Real; σ::Real=1.0)
    s = σ^2
    l <= bbpThreshold(γ; σ) && return 0.0
    return (1 - γ * s^2 / (l - s)^2) / (1 + γ * s / (l - s))
end

"""
    estimateSpike(lambda, gamma; sigma=1.0)

Estimate the population spike `l` from an observed outlier sample eigenvalue
`lambda`, by inverting [`spikeLocation`](@ref):

    l = sigma^2 * ((lam + 1 - gamma) + sqrt((lam + 1 - gamma)^2 - 4 lam)) / 2,
    lam = lambda / sigma^2

For `lambda` at or below the Marcenko-Pastur edge the spike is not
identifiable and the BBP threshold value is returned.
"""
function estimateSpike(λ::Real, γ::Real; σ::Real=1.0)
    s = σ^2
    lam = λ / s
    lam <= (1 + sqrt(γ))^2 && return bbpThreshold(γ; σ)
    return s * ((lam + 1 - γ) + sqrt((lam + 1 - γ)^2 - 4 * lam)) / 2
end

"""
    spikeVariance(l, gamma, n; sigma=1.0, real=true)

Asymptotic variance of the outlier sample eigenvalue generated by a
supercritical population spike `l` (Paul 2007): with `lr = l / sigma^2`,

    Var(lambda_hat) = sigma^4 * 2 lr^2 (1 - gamma / (lr - 1)^2) / n

for real data; `sqrt(n) (lambda_hat - spikeLocation(l, gamma))` is
asymptotically centred normal with variance `n * Var(lambda_hat)`. For
complex data (`real=false`) the variance is halved. Returns `NaN` at or
below the BBP threshold, where the fluctuations are Tracy-Widom rather
than Gaussian.
"""
function spikeVariance(l::Real, γ::Real, n::Integer; σ::Real=1.0, real::Bool=true)
    s = σ^2
    l <= bbpThreshold(γ; σ) && return NaN
    lr = l / s
    v = 2 * lr^2 * (1 - γ / (lr - 1)^2) / n * s^2
    return real ? v : v / 2
end

"""
    svdThreshold(gamma)

Critical population singular value for the rectangular BBP transition
(Benaych-Georges & Nadakuditi): for `p x n` data with `gamma = p/n <= 1` and
noise entries of variance `1/n`, a population singular value `d` produces an
outlier sample singular value only if `d > gamma^(1/4)`.
"""
svdThreshold(γ::Real) = γ^(1 / 4)

"""
    svdSpikeLocation(d, gamma)

Almost-sure limit of the sample singular value generated by a population
singular value `d` in the rectangular spiked model with `gamma = p/n <= 1`:

    sqrt((d^2 + 1) * (1 + gamma / d^2))     if d > gamma^(1/4)

Below the threshold it sticks to the bulk edge `1 + sqrt(gamma)`.
"""
function svdSpikeLocation(d::Real, γ::Real)
    d <= svdThreshold(γ) && return 1 + sqrt(γ)
    return sqrt((d^2 + 1) * (1 + γ / d^2))
end

"""
    svdSpikeOverlaps(d, gamma)

Almost-sure limits `(left, right)` of the squared overlaps between the sample
singular vectors and the population singular vectors for a supercritical
population singular value `d`, with `gamma = p/n <= 1` (`left` is the vector
in `R^p`, `right` the one in `R^n`):

    left  = (d^4 - gamma) / (d^2 * (d^2 + gamma))
    right = (d^4 - gamma) / (d^2 * (d^2 + 1))

Both are zero below the threshold `gamma^(1/4)`.
"""
function svdSpikeOverlaps(d::Real, γ::Real)
    d <= svdThreshold(γ) && return (0.0, 0.0)
    num = d^4 - γ
    return (num / (d^2 * (d^2 + γ)), num / (d^2 * (d^2 + 1)))
end

"""
    randSpikedCovariance(p, n, spikes; sigma=1.0)

Sample covariance matrix `(1/n) X X'` of `p x n` Gaussian data whose
population covariance has eigenvalues `spikes` (a vector of spike
eigenvalues, each `> sigma^2`) on top of a bulk at `sigma^2`, with random
( Haar ) population eigenvectors. Returns a symmetric `p x p` matrix.

# Examples
```julia
S = randSpikedCovariance(200, 400, [4.0])
eigmax(S)   # near spikeLocation(4.0, 0.5) = 4.667
```
"""
function randSpikedCovariance(p::Integer, n::Integer, spikes::AbstractVector{<:Real};
                              σ::Real=1.0)
    k = length(spikes)
    k < p || throw(ArgumentError("need fewer spikes than dimensions"))
    evals = vcat(collect(float.(spikes)), fill(float(σ)^2, p - k))
    Q = Matrix(qr(randn(p, p)).Q)
    A = Q * Diagonal(sqrt.(evals)) * Q'
    X = A * randn(p, n) / sqrt(n)
    return Symmetric(X * X')
end
